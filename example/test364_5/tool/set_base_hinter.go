package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"html/template"
	"io"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"sync"

	"github.com/pkg/errors"
)

func printUsage() {
	_, _ = fmt.Fprintf(os.Stderr, "Usage: %s - <filename>\n", os.Args[0])
}

func printError(err error) {
	_, _ = fmt.Fprintf(os.Stderr, "error: %+v", err)
	fmt.Fprintln(os.Stderr)
	printUsage()

	os.Exit(1)
}

func main() { //nolint:maintidx,gocyclo,funlen
	if len(os.Args) < 3 { //nolint:mnd
		printError(errors.New("<filename> missing"))
	}

	filename := os.Args[2]

	ext := filepath.Ext(filepath.Base(filename))
	if ext != ".go" {
		printError(errors.Errorf("%q: not go file", filename))
	}

	switch fi, err := os.Stat(filename); {
	case os.IsNotExist(err):
		printError(err)
	case fi.IsDir():
		printError(errors.Errorf("%s is not file", filename))
	}

	var source []byte
	switch i, err := os.Open(filepath.Clean(filename)); {
	case err != nil:
		printError(err)
	default:
		b, err := io.ReadAll(i)
		if err != nil {
			printError(err)
		}

		source = b
	}

	fset := token.NewFileSet()

	astfile, err := parser.ParseFile(
		fset,
		filename,
		nil,
		parser.AllErrors,
	)
	if err != nil {
		printError(err)
	}

	var hinters []string

gend:
	for n := range slices.Values(astfile.Decls) {
		gen, ok := n.(*ast.GenDecl)
		if !ok {
			continue gend
		}

		for spec := range slices.Values(gen.Specs) {
			t, ok := spec.(*ast.TypeSpec)
			if !ok {
				continue gend
			}

			if strings.HasSuffix(t.Name.Name, "Marshaler") {
				continue gend
			}

			tspec, ok := t.Type.(*ast.StructType)
			if !ok {
				continue gend
			}

			var found bool

		tsend:
			for field := range slices.Values(tspec.Fields.List) {
				switch tfield := field.Type.(type) {
				case *ast.SelectorExpr:
					if tfield.Sel.Name == "BaseHinter" && tfield.X.(*ast.Ident).Name == "hint" { //nolint:forcetypeassert
						found = true

						break tsend
					}
				}
			}
			if found {
				hinters = append(hinters, t.Name.Name)
			}
		}
	}

	if len(hinters) < 1 {
		return
	}

	receiverNames := map[string]string{}
fend:
	for n := range slices.Values(astfile.Decls) {
		fen, ok := n.(*ast.FuncDecl)
		if !ok || fen.Recv == nil {
			continue fend
		}

	flend:
		for i := range slices.Values(fen.Recv.List) {
			var recv string

			var start token.Pos
			switch ft := i.Type.(type) {
			case *ast.StarExpr:
				recv = ft.X.(*ast.Ident).Name //nolint:forcetypeassert
				start = ft.Star
			case *ast.Ident:
				recv = ft.Name
				start = ft.NamePos
			default:
				continue flend
			}

			switch j := slices.Index(hinters, recv); {
			case j < 0:
				continue fend
			case fen.Name.Name == "SetHint":
				hinters = slices.Delete(hinters, j, j+1)

				continue fend
			default:
				receiverNames[hinters[j]] = strings.TrimSpace(string(source[fen.Recv.Pos() : start-1]))
			}
		}
	}

	var buf *bytes.Buffer

	tmpl, err := template.New("").Parse(setHintTmpl)
	if err != nil {
		printError(err)
	}

	var bufonce sync.Once
	for h := range slices.Values(hinters) {
		bufonce.Do(func() {
			buf = bytes.NewBuffer(nil)
			_, _ = fmt.Fprintf(buf, headTmpl, astfile.Name)
		})

		recv := receiverNames[h]
		if recv == "" {
			recv = "sh"
		}

		if err := tmpl.Execute(buf, map[string]any{
			"receiver": recv,
			"struct":   h,
		}); err != nil {
			printError(err)
		}
	}

	if buf == nil {
		return
	}

	newSource, err := format.Source(buf.Bytes())
	if err != nil {
		printError(err)
	}

	var outf string
	switch {
	case strings.HasSuffix(filename, "_test.go"):
		outf = filename[:len(filename)-8] + "_sh_test.go"
	default:
		outf = filename[:len(filename)-len(ext)] + "_sh.go"
	}

	switch f, err := os.Create(filepath.Clean(outf)); {
	case err != nil:
		printError(err)
	default:
		_, err := f.Write(newSource)
		if err != nil {
			printError(err)
		}
	}

	f, _ := filepath.Abs(filename)

	_, _ = fmt.Fprintf(os.Stdout, "%s: %v\n", f, hinters)
}

var headTmpl = `// Code generated by set_base_hinter.go; DO NOT EDIT.

package %s

import (
	"github.com/spikeekips/mitum/util/hint"
)

`

var setHintTmpl = `func ({{ .receiver }} *{{ .struct }}) SetHint(ht hint.Hint) hint.Hinter {
	if !{{ .receiver }}.BaseHinter.Hint().IsEmpty() {
		return {{ .receiver }}
	}

	{{ .receiver }}.BaseHinter = hint.NewBaseHinter(ht)

	return {{ .receiver }}
}

`
